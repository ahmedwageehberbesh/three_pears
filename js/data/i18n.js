let lang = localStorage.getItem("tb_lang") || "ar";

export const getLang = () => lang;

export const t = (key) => strings[lang][key] ?? strings.ar[key] ?? key;

export const localized = (obj) => (obj && typeof obj === "object" ? obj[lang] ?? obj.ar ?? "" : String(obj ?? ""));

export function setLang(next) {
  lang = next === "en" ? "en" : "ar";
  localStorage.setItem("tb_lang", lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}

export function applyStaticStrings() {
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-label]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nLabel));
  });
}
